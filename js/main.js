/* ============================================================
   reachakash.com — page behaviour
   Every route is a real HTML page (generated by _build/build.js), so
   there's no client-side router: links are plain links and the head
   metadata is already correct. This file only adds enhancements, and
   everything it touches still works with JavaScript off.
   ============================================================ */
document.addEventListener("DOMContentLoaded", function () {

  // ── Theme: dark (default) ⇄ light via the sun/moon button ───────
  // The class lives on <html> and is applied in <head> before first paint.
  // Retro and space stay available from the terminal's `theme` command.
  const THEMES = ['light', 'retro', 'space'];
  const root = document.documentElement;

  function currentTheme() {
    return THEMES.find(function (t) { return root.classList.contains('theme-' + t); }) || 'dark';
  }

  function syncThemeControls() {
    const light = currentTheme() === 'light';
    document.querySelectorAll('[data-theme-toggle]').forEach(function (btn) {
      btn.setAttribute('aria-label', light ? 'Switch to dark theme' : 'Switch to light theme');
    });
    const meta = document.querySelector('meta[name="theme-color"]');
    if (meta) meta.setAttribute('content', light ? '#FFFFFF' : '#181A29');
  }

  window.setSiteTheme = function (name) {
    THEMES.forEach(function (t) { root.classList.remove('theme-' + t); });
    if (name !== 'dark') root.classList.add('theme-' + name);
    if (name === 'retro' && !document.getElementById('font-vt323')) {
      const l = document.createElement('link');
      l.id = 'font-vt323';
      l.rel = 'stylesheet';
      l.href = 'https://fonts.googleapis.com/css2?family=VT323&display=swap';
      document.head.appendChild(l);
    }
    // Save "dark" explicitly: an empty value used to read as "no choice", which
    // let the old retro-theme flag override it on the next page load.
    try { localStorage.setItem('theme', name); localStorage.removeItem('retro-theme'); } catch (e) {}
    syncThemeControls();
  };

  document.querySelectorAll('[data-theme-toggle]').forEach(function (btn) {
    btn.addEventListener('click', function () {
      window.setSiteTheme(currentTheme() === 'light' ? 'dark' : 'light');
    });
  });
  syncThemeControls();

  // ── CTAs read SITE_CONFIG (the generator already rendered the same values) ──
  if (window.siteCta) {
    document.querySelectorAll('[data-cta]').forEach(function (el) {
      const c = window.siteCta(el.dataset.cta);
      if (c) { el.textContent = c.text; el.setAttribute('href', c.href); }
    });
  }

  // ── Mobile menu ─────────────────────────────────────────────────
  const navLinks  = document.getElementById('navLinks');
  const hamburger = document.getElementById('hamburger');
  if (navLinks && hamburger) {
    hamburger.addEventListener('click', function () {
      const open = navLinks.classList.toggle('open');
      hamburger.setAttribute('aria-expanded', open);
      hamburger.setAttribute('aria-label', open ? 'Close menu' : 'Open menu');
    });
  }

  // ── About dropdown (a <details>, so it works without JS too) ────
  const dropdown = document.querySelector('.nav-dropdown');
  if (dropdown) {
    document.addEventListener('click', function (e) {
      if (dropdown.open && !dropdown.contains(e.target)) dropdown.open = false;
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && dropdown.open) {
        dropdown.open = false;
        dropdown.querySelector('summary').focus();
      }
    });
  }

  // ── Slideshow (home) ────────────────────────────────────────────
  const slides = document.querySelectorAll('.home-slide');
  const dots   = document.querySelectorAll('.ss-dot');
  if (slides.length > 1) {
    let cur = 0;
    setInterval(function () {
      slides[cur].classList.remove('active');
      dots[cur]  && dots[cur].classList.remove('active');
      cur = (cur + 1) % slides.length;
      slides[cur].classList.add('active');
      dots[cur]  && dots[cur].classList.add('active');
    }, 15000);
  }

  // ── Contact Form ────────────────────────────────────────────────
  const form = document.getElementById('contact-form');
  if (form) {
    form.addEventListener('submit', async function (e) {
      e.preventDefault();
      const btn    = document.getElementById('form-submit');
      const status = document.getElementById('form-status');

      btn.disabled    = true;
      btn.textContent = 'Sending…';
      status.style.display = 'none';

      try {
        const res  = await fetch(form.action, { method: 'POST', body: new FormData(form) });
        let data;
        try { data = await res.json(); } catch { throw new Error('Could not reach the server. Please email mail@reachakash.com directly.'); }

        if (data.success) {
          status.textContent         = "Message sent! I'll get back to you soon.";
          status.style.background    = 'rgba(var(--accent-rgb), 0.12)';
          status.style.border        = '1px solid rgba(var(--accent-rgb), 0.4)';
          status.style.color         = 'var(--accent)';
          status.style.display       = 'block';
          form.reset();
        } else {
          throw new Error(data.error || 'Something went wrong.');
        }
      } catch (err) {
        status.textContent         = err.message || 'Failed to send. Please try again.';
        status.style.background    = 'rgba(220,50,50,0.1)';
        status.style.border        = '1px solid rgba(220,50,50,0.4)';
        status.style.color         = '#ff6b6b';
        status.style.display       = 'block';
      } finally {
        btn.disabled    = false;
        btn.textContent = 'Send Message';
      }
    });
  }
});
