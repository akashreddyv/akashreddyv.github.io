#!/usr/bin/env node
/* ============================================================
   reachakash.com page generator. No dependencies.

     node _build/build.js           write every generated file
     node _build/build.js --check   exit 1 if any generated file is stale

   Inputs:  _build/template.html, _build/routes.js, pages/*.html, images/brand/lockup.svg,
            _build/data/referrals.json (via _build/referrals.js), _build/data/photos.json,
            js/site-config.js (CTA text/links, same rules as the browser)
   Outputs: one HTML file per route at the repo root (GitHub Pages serves
            /about from about.html with a 200), one page per referral offer
            and category in referrals/, 404.html, sitemap.xml, llms.txt,
            referrals.json. Outputs are committed; edit the inputs, never them.
   ============================================================ */
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const CHECK = process.argv.includes('--check');
// Normalise to LF: git on Windows checks files out with CRLF, and the output
// must not depend on how the inputs happen to be checked out.
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8').replace(/\r\n/g, '\n');

const { site, routes, llms } = require('./routes.js');
const referrals = require('./referrals.js');
const template = read('_build/template.html');

// Run the browser config file so generated HTML matches what JS would render.
const sandbox = { window: {} };
vm.runInNewContext(read('js/site-config.js'), sandbox, { filename: 'js/site-config.js' });
const cta = sandbox.window.siteCta('primary', sandbox.window.SITE_CONFIG);

const YEAR = String(new Date().getFullYear());
const TODAY = new Date().toISOString().slice(0, 10);

const escAttr = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function generatedNote(sources) {
  return `<!-- GENERATED by _build/build.js. Do not edit this file: edit ${sources.join(', ')}, then run \`node _build/build.js\`. -->`;
}

function fill(tpl, values) {
  return tpl.replace(/\{\{(\w+)\}\}/g, (m, key) => {
    if (!(key in values)) throw new Error(`template placeholder {{${key}}} has no value`);
    return values[key];
  });
}

// Inline copies of images/brand/lockup.svg so its layers (logo-curve, logo-step-01..08) can animate
// (css/styles.css, "LOGO INTRO"). The curve sits under a clip whose rect grows upward during the intro.
//   header: the full lockup in the nav (keeps the layer ids)
//   mark:   just the steps and curve, beside the name on Home (ids dropped so they stay unique on the page)
const LOCKUP = (() => {
  const m = read('images/brand/lockup.svg').match(/<symbol id="lockup" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/);
  if (!m || !/id="logo-step-08"/.test(m[2])) throw new Error('images/brand/lockup.svg is not layered (expected logo-curve and logo-step-01..08)');
  return { viewBox: m[1], body: m[2].replace(/<title>[\s\S]*?<\/title>\n?/, '').trim() };
})();
function inlineLogo({ cls, viewBox, clipId, word, keepIds }) {
  let body = LOCKUP.body.replace('<g id="logo-curve" class="logo-curve">', `<g id="logo-curve" class="logo-curve" clip-path="url(#${clipId})">`);
  if (!word) body = body.replace(/\n?<g class="logo-word"[\s\S]*?<\/g>/, '');
  if (!keepIds) body = body.replace(/ id="logo-(?:curve|step-\d\d)"/g, '');
  return [
    `<svg class="${cls}" viewBox="${viewBox}" aria-hidden="true" focusable="false">`,
    `<defs><clipPath id="${clipId}" clipPathUnits="userSpaceOnUse"><rect class="logo-curve-wipe" x="500" y="340" width="380" height="560"/></clipPath></defs>`,
    body,
    '</svg>'
  ].join('\n');
}
const LOGO_HEADER = inlineLogo({ cls: 'brand-lockup logo-anim', viewBox: LOCKUP.viewBox, clipId: 'logo-curve-clip', word: true, keepIds: true });
// Mark bounds x 83.8..833.0, y 370.4..872.6, plus 20 units so a popping bottom step isn't clipped.
const LOGO_MARK = inlineLogo({ cls: 'home-mark logo-anim', viewBox: '63.8 350.4 789.2 542.2', clipId: 'home-mark-curve-clip', word: false, keepIds: false });

// FAQPage JSON-LD built from the page's own questions (<div class="faq-item"><h3>Q</h3><p>A</p></div>),
// so the markup always matches what visitors read.
const plain = (html) => html.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim()
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");
function faqJsonLd(html, route) {
  const items = [...html.matchAll(/<div class="faq-item">\s*<h3>([\s\S]*?)<\/h3>\s*<p>([\s\S]*?)<\/p>\s*<\/div>/g)]
    .map(([, q, a]) => ({ '@type': 'Question', name: plain(q), acceptedAnswer: { '@type': 'Answer', text: plain(a) } }));
  if (!items.length) throw new Error(`${route.out}: faq is on but the page has no .faq-item blocks`);
  return { '@context': 'https://schema.org', '@type': 'FAQPage', '@id': site.origin + route.path + '#faq', mainEntity: items };
}

function jsonLd(objects) {
  // Guard against "</script>" inside strings ending the block early.
  return JSON.stringify(objects, null, 2).replace(/<\//g, '<\\/').replace(/^/gm, '  ');
}

const warnings = [];

// Referral entries: published, not expired. Stale lastVerified dates only warn.
const REF = referrals.load(read('_build/data/referrals.json'), TODAY);
warnings.push(...REF.warnings);
for (const e of REF.live) {
  if (e.logo && !fs.existsSync(path.join(ROOT, e.logo))) throw new Error(`referrals.json "${e.id}": logo file ${e.logo} does not exist`);
}

// Pixel size of a JPEG, PNG or WebP, read from its header (no dependencies).
function imageSize(file) {
  const b = fs.readFileSync(file);
  if (b[0] === 0x89 && b.toString('ascii', 1, 4) === 'PNG') return [b.readUInt32BE(16), b.readUInt32BE(20)];
  if (b.toString('ascii', 0, 4) === 'RIFF' && b.toString('ascii', 8, 12) === 'WEBP') {
    const kind = b.toString('ascii', 12, 16);
    if (kind === 'VP8X') return [1 + b.readUIntLE(24, 3), 1 + b.readUIntLE(27, 3)];
    if (kind === 'VP8L') { const v = b.readUInt32LE(21); return [1 + (v & 0x3FFF), 1 + ((v >> 14) & 0x3FFF)]; }
    return [b.readUInt16LE(26) & 0x3FFF, b.readUInt16LE(28) & 0x3FFF];
  }
  for (let i = 2; i < b.length;) {                       // JPEG: walk to the SOF marker
    const marker = b[i + 1];
    if (marker >= 0xC0 && marker <= 0xCF && ![0xC4, 0xC8, 0xCC].includes(marker)) return [b.readUInt16BE(i + 7), b.readUInt16BE(i + 5)];
    i += 2 + b.readUInt16BE(i + 2);
  }
  throw new Error(`can't read the size of ${file}`);
}

// Photos of Akash for the Photos section of /gallery (_build/data/photos.json).
const PHOTOS = JSON.parse(read('_build/data/photos.json')).photos;
for (const p of PHOTOS) {
  for (const f of ['file', 'width', 'height', 'title', 'alt', 'caption']) {
    if (!p[f]) throw new Error(`photos.json: ${p.file || '(no file)'} is missing ${f}`);
  }
  const abs = path.join(ROOT, p.file);
  if (!fs.existsSync(abs)) throw new Error(`photos.json: ${p.file} does not exist`);
  const [w, h] = imageSize(abs);
  if (w !== p.width || h !== p.height) throw new Error(`photos.json: ${p.file} is ${w}x${h}, not ${p.width}x${p.height}`);
  if (/\.jpe?g$/i.test(p.file) && !fs.readFileSync(abs).includes('Iptc4xmpExt:PersonInImage')) {
    warnings.push(`photos.json: ${p.file} has no XMP tags yet; run node _build/photo-meta.js`);
  }
}
const photoGallery = PHOTOS.length
  ? [
      '    <div class="gallery-grid">',
      ...PHOTOS.map((p, i) => [
        '      <figure class="gallery-item">',
        `        <a href="${escAttr(p.file)}" target="_blank" rel="noopener"><img src="${escAttr(p.file)}" alt="${escAttr(p.alt)}" width="${p.width}" height="${p.height}"${i < 2 ? '' : ' loading="lazy"'} decoding="async"></a>`,
        `        <figcaption>${escAttr(p.caption)}</figcaption>`,
        '      </figure>'
      ].join('\n')),
      '    </div>'
    ].join('\n')
  : '    <p class="brand-gallery-intro">Photos are on their way.</p>';

// Every page: the hand-written routes plus one per referral offer and category
// (those carry their HTML in `content` instead of a pages/ partial).
const ALL = [...routes, ...referrals.pages(REF, site.origin)];
const seen = new Set();
for (const r of ALL) {
  if (seen.has(r.out)) throw new Error(`two pages write ${r.out}`);
  seen.add(r.out);
}

function renderPage(route) {
  const source = (route.content != null ? route.content : read(route.source))
    .replace(/<script[\s\S]*?<\/script>/gi, '');           // partials never shipped scripts

  const content = fill(source, {
    ctaPrimaryText: escAttr(cta.text),
    ctaPrimaryHref: escAttr(cta.href),
    referralJump: referrals.renderJump(REF.groups),
    referralSections: referrals.renderSections(REF.groups),
    photoGallery,
    logoMark: LOGO_MARK
  });

  const canonical = route.notFound ? null : site.origin + route.path;
  const noindex = route.draft || route.notFound;

  if (!noindex) {
    if (route.title.length > 60) warnings.push(`${route.out}: title is ${route.title.length} chars (max 60)`);
    if (route.description.length > 155) warnings.push(`${route.out}: description is ${route.description.length} chars (max 155)`);
  }

  let headExtra = route.headExtra || '';
  if (route.notFound) {
    // Old links sometimes add a trailing slash (/about/). Send known routes home.
    const known = ALL.filter((r) => r.path && r.path !== '/').map((r) => r.path);
    headExtra += [
      '  <script>',
      `    (function () { var known = ${JSON.stringify(known)};`,
      "      var p = location.pathname.replace(/\\/+$/, '');",
      '      if (p !== location.pathname && known.indexOf(p) !== -1) location.replace(p + location.search + location.hash); })();',
      '  </script>'
    ].join('\n') + '\n';
  }

  // /referrals also lists every offer page as an ItemList.
  let ld = route.slug === 'referrals'
    ? [...route.jsonld, { '@context': 'https://schema.org', ...referrals.itemList(REF.live, site.origin) }]
    : route.jsonld;
  if (route.faq) ld = [...ld, faqJsonLd(content, route)];

  let html = fill(template, {
    generatedNote: generatedNote(route.source
      ? ['_build/template.html', '_build/routes.js', route.source]
      : ['_build/template.html', '_build/data/referrals.json', '_build/referrals.js']),
    title: escAttr(route.title),
    description: escAttr(route.description),
    robotsTag: noindex ? '  <meta name="robots" content="noindex">\n' : '',
    canonicalTag: canonical ? `  <link rel="canonical" href="${canonical}">\n` : '',
    ogType: route.ogType,
    ogUrl: canonical || site.origin + '/',
    ogTitle: escAttr(route.ogTitle),
    ogDesc: escAttr(route.ogDesc),
    ogImage: site.ogImage,
    ogImageAlt: escAttr(site.ogImageAlt),
    ogProfile: route.ogType === 'profile'
      ? '  <meta property="profile:first_name" content="Akash">\n  <meta property="profile:last_name"  content="Reddy">\n'
      : '',
    headExtra,
    jsonld: jsonLd(ld),
    slug: route.slug,
    content,
    year: YEAR,
    ctaPrimaryText: escAttr(cta.text),
    ctaPrimaryHref: escAttr(cta.href),
    logoHeader: LOGO_HEADER
  });

  // Mark the current page in the nav ("true" rather than "page" on pages inside a section).
  if (route.nav) {
    html = html.replace(`data-nav="${route.nav}"`, `data-nav="${route.nav}" aria-current="${route.navCurrent || 'page'}"`);
  }
  if (route.navGroup) {
    html = html.replace(`<summary data-nav-group="${route.navGroup}">`,
                        `<summary data-nav-group="${route.navGroup}" class="is-current">`);
  }
  return html;
}

function renderRedirect(route) {
  const target = site.origin + route.redirectTo;
  // A title unique to each redirect: Bing flags pages that share one, even noindex redirects.
  const host = site.origin.replace(/^https:\/\//, '');
  return [
    '<!DOCTYPE html>',
    generatedNote(['_build/routes.js']),
    '<html lang="en">',
    '<head>',
    '  <meta charset="UTF-8">',
    `  <title>${host}${route.path} moved to ${host}${route.redirectTo}</title>`,
    `  <link rel="canonical" href="${target}">`,
    '  <meta name="robots" content="noindex">',
    `  <meta http-equiv="refresh" content="0; url=${route.redirectTo}">`,
    '</head>',
    '<body>',
    `  <p>This page moved to <a href="${route.redirectTo}">${host}${route.redirectTo}</a>.</p>`,
    '</body>',
    '</html>',
    ''
  ].join('\n');
}

function renderSitemap() {
  const entries = ALL
    .filter((r) => r.path && !r.draft && !r.redirectTo && !r.notFound && r.sitemap)
    .map((r) => {
      const lines = [
        '  <url>',
        `    <loc>${site.origin}${r.path}</loc>`,
        // Only where the date is real (referral pages: the day the offer was last checked).
        ...(r.sitemap.lastmod ? [`    <lastmod>${r.sitemap.lastmod}</lastmod>`] : []),
        `    <changefreq>${r.sitemap.changefreq}</changefreq>`,
        `    <priority>${r.sitemap.priority}</priority>`
      ];
      for (const [loc, title] of r.sitemap.images || []) {
        lines.push('    <image:image>', `      <image:loc>${loc}</image:loc>`,
                   `      <image:title>${escAttr(title)}</image:title>`, '    </image:image>');
      }
      lines.push('  </url>');
      return lines.join('\n');
    });
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    generatedNote(['_build/routes.js']),
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
    '        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">',
    ...entries,
    '</urlset>',
    ''
  ].join('\n');
}

function renderLlms() {
  const pages = routes
    .filter((r) => r.path && !r.draft && !r.redirectTo && !r.notFound && r.llms)
    .map((r) => `- [${r.slug === 'home' ? 'Home' : r.slug[0].toUpperCase() + r.slug.slice(1)}](${site.origin}${r.path}): ${r.llms}`);
  const out = [`# ${llms.title}`, '', `> ${llms.summary}`, '', '## Pages', '', ...pages];
  for (const [heading, items] of llms.sections) out.push('', `## ${heading}`, '', ...items.map((i) => `- ${i}`));
  if (REF.live.length) {
    out.push('', '## Referral codes', '',
      `Akash Reddy's referral codes and links, each with its own page (code, what you get, steps, official terms), last checked ${REF.updated}. ` +
      `He earns a reward when people sign up through them. All of them: ${site.origin}/referrals. Machine-readable: ${site.origin}/referrals.json`, '',
      '### By category', '',
      ...referrals.llmsCategories(REF, site.origin).map((i) => `- ${i}`), '',
      '### Every offer', '',
      ...referrals.llmsLines(REF, site.origin).map((i) => `- ${i}`));
  }
  // llms.txt must open with its H1, so the generated notice goes at the end.
  out.push('', generatedNote(['_build/routes.js', '_build/data/referrals.json']), '');
  return out.join('\n');
}

// ── Build everything in memory ───────────────────────────────────
const outputs = new Map();
for (const route of ALL) {
  outputs.set(route.out, route.redirectTo ? renderRedirect(route) : renderPage(route));
}
// A referrals/ page whose offer was unpublished would otherwise linger, live and stale.
const refDir = path.join(ROOT, 'referrals');
if (fs.existsSync(refDir)) {
  for (const f of fs.readdirSync(refDir)) {
    if (!outputs.has(`referrals/${f}`)) warnings.push(`referrals/${f} is no longer generated; delete it`);
  }
}
outputs.set('sitemap.xml', renderSitemap());
outputs.set('llms.txt', renderLlms());
outputs.set('referrals.json', referrals.renderJson(REF, site.origin,
  'GENERATED by _build/build.js from _build/data/referrals.json. Do not edit this file: edit the data file, then run node _build/build.js.'));

// ── Write or check ───────────────────────────────────────────────
const normalise = (s) => s.replace(/\r\n/g, '\n');
let stale = 0;

for (const [file, body] of outputs) {
  const target = path.join(ROOT, file);
  const current = fs.existsSync(target) ? normalise(fs.readFileSync(target, 'utf8')) : null;
  if (current === body) continue;
  if (CHECK) {
    stale++;
    console.error(`stale: ${file}${current === null ? ' (missing)' : ''}`);
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, body);
    console.log(`wrote ${file}`);
  }
}

for (const w of warnings) console.warn(`warning: ${w}`);

if (CHECK) {
  if (stale) {
    console.error(`\n${stale} generated file(s) out of date. Run: node _build/build.js`);
    process.exit(1);
  }
  console.log(`ok: ${outputs.size} generated files are up to date`);
} else {
  console.log(`done: ${outputs.size} files checked`);
}
